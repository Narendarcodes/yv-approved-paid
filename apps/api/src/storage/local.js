const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const config = require('../config');

/**
 * Local-disk storage adapter (MVP).
 * The storage boundary means a cloud object store can be swapped in later
 * without touching services/controllers.
 */
const UPLOAD_DIR = config.storage.localDir;

function ensureDir() {
  if (!fs.existsSync(UPLOAD_DIR)) {
    fs.mkdirSync(UPLOAD_DIR, { recursive: true });
  }
}

/**
 * @param {Buffer|string} data file bytes
 * @param {{filename:string, mimeType?:string}} meta
 * @returns {Promise<{storageRef:string, size:number}>}
 */
async function saveFile(data, meta) {
  ensureDir();
  const id = crypto.randomBytes(16).toString('hex');
  const ext = path.extname(meta.filename || '');
  const storageName = `${id}${ext}`;
  const full = path.join(UPLOAD_DIR, storageName);
  await fs.promises.writeFile(full, data);
  return { storageRef: storageName, size: Buffer.byteLength(data) };
}

// Refs are generated by saveFile: 32 hex chars + optional short extension.
// Anything else (../, slashes, absolute paths) is rejected, so a stored ref can
// never point outside UPLOAD_DIR.
const REF_RE = /^[a-f0-9]{32}(\.[A-Za-z0-9]{1,10})?$/;

/** Absolute path of a stored file, or null if the ref is malformed. */
function resolvePath(storageRef) {
  if (typeof storageRef !== 'string' || !REF_RE.test(storageRef)) return null;
  return path.join(UPLOAD_DIR, storageRef);
}

async function getFile(storageRef) {
  const full = resolvePath(storageRef);
  if (!full) throw { status: 404, code: 'file_not_found', message: 'File not found' };
  if (!fs.existsSync(full))
    throw { status: 404, code: 'file_not_found', message: 'File not found' };
  return fs.promises.readFile(full);
}

module.exports = { saveFile, getFile, resolvePath };
